def flag(parent, name, value=None):
    el = OxmlElement("w:" + name)
    if value is not None:
        el.set(qn("w:val"), value)
    parent.append(el)
    return el

def format_run(run, size=11, bold=False):
    run.font.name = "DejaVu Sans"
    run.font.size = Pt(size)
    run.bold = bold
    props = run._element.get_or_add_rPr()
    fonts = props.rFonts
    if fonts is not None:
        fonts.set(qn("w:cs"), "DejaVu Sans")
    flag(props, "rtl")
    flag(props, "szCs", str(size * 2))
    if bold:
        flag(props, "bCs")

def rtl(p):
    p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    flag(p._p.get_or_add_pPr(), "bidi")
    p.paragraph_format.space_after = Pt(7)
    p.paragraph_format.line_spacing = 1.15
    return p

def para(text, size=11):
    p = rtl(doc.add_paragraph())
    format_run(p.add_run(text), size)
    return p

def heading(text, level=1):
    p = rtl(doc.add_paragraph(style=f"Heading {level}"))
    r = p.add_run(text)
    format_run(r, 20 if level == 1 else 13, True)
    r.font.color.rgb = RGBColor.from_string("124E61")
    p.paragraph_format.space_before = Pt(9)
    p.paragraph_format.space_after = Pt(8)
    return p

def page(title):
    doc.add_page_break()
    heading(title)

def bullets(items):
    for item in items:
        para("• " + item)

def table(headers, rows):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Light Shading Accent 1"
    flag(t._tbl.tblPr, "bidiVisual")
    for i, val in enumerate(headers):
        p = rtl(t.rows[0].cells[i].paragraphs[0])
        format_run(p.add_run(val), 10, True)
    flag(t.rows[0]._tr.get_or_add_trPr(), "tblHeader")
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            p = rtl(cells[i].paragraphs[0])
            p.paragraph_format.space_after = Pt(4)
            format_run(p.add_run(str(val)), 10)
    for row in t.rows:
        flag(row._tr.get_or_add_trPr(), "cantSplit")
    para("")

count = 0
def picture(path, caption, height=3.1):
    global count
    with Image.open(path) as im:
        w,h=im.size
    p=doc.add_paragraph()
    p.alignment=WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.keep_with_next=True
    p.add_run().add_picture(str(path),width=Inches(min(6.8,height*w/h)))
    count+=1
    p=para(f"الشكل {count}: {caption}",9)
    p.alignment=WD_ALIGN_PARAGRAPH.CENTER

